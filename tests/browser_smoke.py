"""Optional UI verification. Install playwright and its Chromium separately.

Executed by verify_native.py --browser tests/browser_smoke.py.
PARKING_BROWSER may select an existing Chromium executable.
"""
import os
import uuid
from pathlib import Path

from playwright.sync_api import sync_playwright,expect


def main():
    output=Path(os.environ.get("QA_OUTPUT",".local/browser-qa"));output.mkdir(parents=True,exist_ok=True)
    with sync_playwright() as p:
        options={"headless":True,"args":["--no-sandbox","--disable-dev-shm-usage","--single-process","--no-zygote"]}
        if os.getenv("PARKING_BROWSER"):options["executable_path"]=os.environ["PARKING_BROWSER"]
        browser=p.chromium.launch(**options)
        page=browser.new_page(viewport={"width":1440,"height":1000},locale="ru-RU",timezone_id="Europe/Chisinau")
        errors=[];page.on("pageerror",lambda e:errors.append(str(e)))
        base_url=os.environ.get("E2E_URL","http://127.0.0.1:8080")
        page.goto(base_url)
        expect(page.locator(".lot-card").first).to_be_visible()
        expect(page.locator("#connection-text")).to_have_text("Все сервисы готовы",timeout=20000)
        start=page.locator('#start-at').input_value()
        end=page.locator('#end-at').input_value()
        page.screenshot(path=str(output/"parking-desktop.png"),full_page=True)
        page.locator("#auth-button").click();page.locator("#auth-toggle").click()
        form=page.locator("#auth-form")
        form.locator('[name="name"]').fill("Проверка интерфейса")
        form.locator('[name="email"]').fill("browser-"+uuid.uuid4().hex+"@example.test")
        form.locator('[name="password"]').fill("Browser-password-123")
        page.locator("#auth-submit").click()
        expect(page.locator("#auth-dialog")).not_to_be_visible()
        page.locator('nav [data-view="profile"]').click()
        form=page.locator("#vehicle-form")
        form.locator('[name="plate"]').fill("UI 123")
        form.locator('[name="label"]').fill("Тестовый автомобиль")
        form.locator('button[type="submit"],button:not([type])').click()
        expect(page.locator(".plate")).to_have_text("UI 123")
        page.locator('nav [data-view="parking"]').click()
        page.locator("[data-lot]").first.click()
        page.locator("[data-space]:not([disabled])").first.click()
        page.locator("#promo-code").fill("PARK10")
        page.locator("#apply-promo").click()
        expect(page.locator("#promo-feedback")).to_contain_text("Скидка:")
        page.locator("#book-button").click()
        expect(page.locator("#payment-dialog")).to_be_visible()
        page.locator("#payment-submit").click()
        expect(page.locator("#payment-dialog")).not_to_be_visible()
        expect(page.locator(".badge.CONFIRMED")).to_be_visible(timeout=25000)
        expect(page.locator(".data-table")).to_contain_text("PARK10")
        page.screenshot(path=str(output/"bookings-desktop.png"),full_page=True)
        page.once("dialog",lambda d:d.accept())
        page.locator("[data-cancel]").first.click()
        expect(page.locator(".badge.CANCELLED")).to_be_visible()
        page.locator('nav [data-view="payments"]').click()
        expect(page.locator(".badge.REFUNDED")).to_be_visible(timeout=25000)
        page.locator('nav [data-view="notifications"]').click()
        expect(page.locator(".notification").first).to_be_visible()
        page.locator("[data-read]").first.click()
        admin=browser.new_page(viewport={"width":1440,"height":1000},locale="ru-RU",timezone_id="Europe/Chisinau")
        admin.on("pageerror",lambda e:errors.append(str(e)))
        admin.goto(base_url)
        admin.locator("#auth-button").click()
        form=admin.locator("#auth-form")
        form.locator('[name="email"]').fill(os.environ["E2E_ADMIN_EMAIL"])
        form.locator('[name="password"]').fill(os.environ["E2E_ADMIN_PASSWORD"])
        admin.locator("#auth-submit").click()
        expect(admin.locator("#admin-nav")).to_be_visible()
        admin.locator("#admin-nav").click()
        expect(admin.locator("#lot-form")).to_be_visible()
        form=admin.locator("#lot-form")
        form.locator('[name="name"]').fill("Парковка из UI")
        form.locator('[name="address"]').fill("Тестовая улица, 30")
        form.locator('[name="capacity"]').fill("1")
        form.locator("button").click()
        expect(admin.locator(".admin-row").filter(has_text="Парковка из UI")).to_be_visible()
        admin.screenshot(path=str(output/"admin-desktop.png"),full_page=True)
        lot=next(l for l in admin.request.get(base_url+"/api/parking/lots").json()
                 if l["name"]=="Парковка из UI")
        admin.locator('nav [data-view="promotions"]').click()
        promo=admin.locator("#promotion-form")
        code="UITEST"+uuid.uuid4().hex[:6].upper()
        promo.locator('[name="code"]').fill(code)
        promo.locator('[name="percent"]').fill("15")
        promo.locator('button[type="submit"]').click()
        expect(admin.locator(".data-table")).to_contain_text(code)
        admin.locator('nav [data-view="maintenance"]').click()
        maintenance=admin.locator("#maintenance-form")
        maintenance.locator('[name="lot_id"]').select_option(lot["id"])
        expect(maintenance.locator('[name="space_id"] option')).to_have_count(1)
        maintenance.locator('[name="start_at"]').fill(start)
        maintenance.locator('[name="end_at"]').fill(end)
        maintenance.locator('[name="reason"]').fill("Ремонт тестового места")
        maintenance.locator('button[type="submit"]').click()
        work=admin.locator(".data-table tbody tr").filter(has_text="Ремонт тестового места")
        expect(work.locator(".badge.ACTIVE")).to_be_visible()
        page.locator('nav [data-view="parking"]').click()
        page.locator(".lot-card").filter(has_text="Парковка из UI").locator("[data-lot]").click()
        expect(page.locator(".under-maintenance")).to_be_disabled()
        page.locator("#join-waitlist").click()
        expect(page.locator(".badge.WAITING")).to_be_visible()
        work.locator("[data-cancel-maintenance]").click()
        expect(work.locator(".badge.CANCELLED")).to_be_visible()
        expect(page.locator(".badge.OFFERED")).to_be_visible(timeout=25000)
        page.locator("[data-wait-offer]").click()
        expect(page.locator(".space.selected")).to_be_visible()
        expect(page.locator("#book-button")).to_be_enabled()
        admin.locator('nav [data-view="reports"]').click()
        expect(admin.locator(".report-card")).to_have_count(4)
        expect(admin.locator(".report-grid")).to_contain_text("Учебные оплаты")
        admin.screenshot(path=str(output/"reports-desktop.png"),full_page=True)
        page.set_viewport_size({"width":390,"height":844})
        page.locator('nav [data-view="parking"]').click()
        expect(page.locator(".lot-card").first).to_be_visible()
        page.screenshot(path=str(output/"parking-mobile.png"),full_page=True)
        overflow=page.evaluate("Array.from(document.querySelectorAll('body *')).filter(x=>x.getBoundingClientRect().right>innerWidth+1).map(x=>({tag:x.tagName,class:x.className,width:x.getBoundingClientRect().width})).slice(0,12)")
        assert page.evaluate("document.documentElement.scrollWidth<=window.innerWidth"),f"Horizontal overflow on mobile: {overflow}"
        assert not errors,errors
        browser.close()
    print("Browser: original flow, discount, promotion admin, maintenance, waitlist, reporting and mobile passed.",flush=True)


if __name__=="__main__":main()
